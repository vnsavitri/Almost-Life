import { useState, useEffect, useCallback } from "react";
import { useLocation, Link } from "wouter";
import type { LifeData } from "@/lib/types";
import LinkedInGhost from "@/components/templates/LinkedInGhost";
import WikiStub from "@/components/templates/WikiStub";
import MuseumPlaque from "@/components/templates/MuseumPlaque";
import TarotCard from "@/components/templates/TarotCard";

type TemplateKey = "linkedin_ghost" | "wiki_stub" | "museum_plaque" | "tarot_card";

const TEMPLATES: { key: TemplateKey; label: string; sub: string }[] = [
  { key: "linkedin_ghost", label: "LinkedIn Ghost", sub: "Other You, hireable" },
  { key: "wiki_stub", label: "The Wiki Stub", sub: "Notable. Probably." },
  { key: "museum_plaque", label: "Museum Plaque", sub: "80 words. All restraint." },
  { key: "tarot_card", label: "The Tarot Card", sub: "Cards don't lie." },
];

type CoreData = Omit<LifeData, "linkedin_ghost" | "wiki_stub" | "museum_plaque" | "tarot_card">;

function buildFullData(core: CoreData, templateKey: TemplateKey, templateData: unknown): LifeData {
  return { ...core, [templateKey]: templateData } as LifeData;
}

function downloadHtml(core: CoreData, templateKey: TemplateKey, templateData: unknown) {
  const labels: Record<TemplateKey, string> = {
    linkedin_ghost: "LinkedIn Ghost",
    wiki_stub: "Wiki Stub",
    museum_plaque: "Museum Plaque",
    tarot_card: "Tarot Card",
  };
  const blob = new Blob([
    `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8"><title>Almost — ${core.name} — ${labels[templateKey]}</title>` +
    `<link href="https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,300;0,9..144,400;1,9..144,300&family=Inter:wght@300;400;500&display=swap" rel="stylesheet">` +
    `<style>*{box-sizing:border-box;margin:0;padding:0}body{font-family:'Inter',sans-serif}</style></head>` +
    `<body><p style="text-align:center;padding:2rem;font-family:'Fraunces',serif;font-style:italic;opacity:.4">Generated by Almost — the life you didn't quite live</p></body></html>`
  ], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `almost-${core.name.toLowerCase().replace(/\s+/g, "-")}-${templateKey}.html`;
  a.click();
  URL.revokeObjectURL(url);
}

export default function Result() {
  const [, navigate] = useLocation();
  const [core, setCore] = useState<CoreData | null>(null);
  const [templateCache, setTemplateCache] = useState<Partial<Record<TemplateKey, unknown>>>({});
  const [loadingTemplate, setLoadingTemplate] = useState<TemplateKey | null>(null);
  const [selected, setSelected] = useState<TemplateKey>("linkedin_ghost");
  const [genError, setGenError] = useState<string | null>(null);

  // Load core + first template from sessionStorage on mount
  useEffect(() => {
    const coreRaw = sessionStorage.getItem("almost_life_core");
    const lgRaw = sessionStorage.getItem("almost_life_linkedin_ghost");

    if (!coreRaw || !lgRaw) {
      // Nothing generated yet — bail back
      const branchRaw = sessionStorage.getItem("almost_branch");
      if (!branchRaw) { navigate("/upload"); return; }
      // Try to recover from old single-blob format
      const legacyRaw = sessionStorage.getItem("almost_life");
      if (legacyRaw) {
        try {
          const legacy = JSON.parse(legacyRaw) as LifeData;
          const { linkedin_ghost, wiki_stub, museum_plaque, tarot_card, ...legacyCore } = legacy;
          setCore(legacyCore);
          const cache: Partial<Record<TemplateKey, unknown>> = {};
          if (linkedin_ghost) cache.linkedin_ghost = linkedin_ghost;
          if (wiki_stub) cache.wiki_stub = wiki_stub;
          if (museum_plaque) cache.museum_plaque = museum_plaque;
          if (tarot_card) cache.tarot_card = tarot_card;
          setTemplateCache(cache);
          return;
        } catch { /* fall through */ }
      }
      navigate("/upload");
      return;
    }

    try {
      setCore(JSON.parse(coreRaw));
      setTemplateCache({ linkedin_ghost: JSON.parse(lgRaw) });
    } catch {
      navigate("/upload");
    }
  }, [navigate]);

  const generateTemplate = useCallback(async (key: TemplateKey) => {
    if (templateCache[key] || loadingTemplate) return;

    const branchRaw = sessionStorage.getItem("almost_branch");
    if (!branchRaw) return;
    const branch = JSON.parse(branchRaw);
    const isDemo = sessionStorage.getItem("almost_demo") === "true";
    const pdfB64 = sessionStorage.getItem("almost_pdf_b64");

    setLoadingTemplate(key);
    setGenError(null);

    try {
      const r = await fetch("/api/generate-life", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          branch,
          template_type: key,
          demo: isDemo || undefined,
          pdf_b64: pdfB64 || undefined,
        }),
      });

      if (!r.ok) throw new Error("Generation failed");
      const data = await r.json();

      if (data.life?.[key]) {
        // Update core if we got better data
        const { [key]: templateData, ...newCore } = data.life;
        setCore((prev) => prev ? { ...prev, ...newCore } : newCore);
        setTemplateCache((prev) => {
          const next = { ...prev, [key]: templateData };
          sessionStorage.setItem(`almost_life_${key}`, JSON.stringify(templateData));
          return next;
        });
      }
    } catch {
      setGenError("Generation timed out. Try again.");
    } finally {
      setLoadingTemplate(null);
    }
  }, [templateCache, loadingTemplate]);

  const handleSelectTemplate = (key: TemplateKey) => {
    setSelected(key);
    if (!templateCache[key]) generateTemplate(key);
  };

  if (!core) {
    return (
      <main style={{ backgroundColor: "#F5EFE6", minHeight: "100vh", display: "flex", alignItems: "center", justifyContent: "center" }}>
        <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", opacity: 0.4 }}>Assembling the other version...</p>
      </main>
    );
  }

  const currentTemplateData = templateCache[selected];
  const fullData = currentTemplateData ? buildFullData(core, selected, currentTemplateData) : null;

  return (
    <main style={{ backgroundColor: "#F5EFE6", color: "#1A1A1A", minHeight: "100vh" }}>

      {/* Header */}
      <div style={{ backgroundColor: "#F5EFE6", borderBottom: "1px solid rgba(26,26,26,0.1)", padding: "1rem 1.5rem", display: "flex", alignItems: "center", justifyContent: "space-between", position: "sticky", top: 0, zIndex: 10 }}>
        <Link href="/branches">
          <span style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", color: "#1A1A1A", opacity: 0.4, letterSpacing: "0.04em", cursor: "pointer" }}>
            ← Try another fork
          </span>
        </Link>
        <span style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontSize: "0.875rem", opacity: 0.5 }}>Almost</span>
        <button
          onClick={() => fullData && downloadHtml(core, selected, currentTemplateData)}
          disabled={!fullData}
          style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", backgroundColor: fullData ? "#1A1A1A" : "rgba(26,26,26,0.2)", color: "#F5EFE6", border: "none", padding: "0.5rem 1.25rem", cursor: fullData ? "pointer" : "default", letterSpacing: "0.04em", transition: "background-color 0.2s" }}
        >
          Download →
        </button>
      </div>

      {/* Fork summary */}
      <div style={{ padding: "2.5rem 1.5rem 1.5rem", maxWidth: "680px", margin: "0 auto" }}>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", letterSpacing: "0.1em", textTransform: "uppercase", opacity: 0.35, marginBottom: "0.5rem" }}>
          {core.year_of_fork} · the road not taken
        </p>
        <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "clamp(1.5rem, 4vw, 2rem)", fontWeight: 300, lineHeight: 1.2, marginBottom: "0.4rem" }}>
          {core.fork_summary}
        </h1>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.875rem", opacity: 0.5 }}>
          {core.alt_role} · {core.alt_location}
        </p>
      </div>

      {/* Template picker */}
      <div style={{ padding: "0 1.5rem 1.5rem", maxWidth: "680px", margin: "0 auto" }}>
        <div style={{ display: "grid", gridTemplateColumns: "repeat(2, 1fr)", gap: "0.5rem" }}>
          {TEMPLATES.map((t) => {
            const isSelected = selected === t.key;
            const isCached = !!templateCache[t.key];
            const isGenerating = loadingTemplate === t.key;
            return (
              <button
                key={t.key}
                onClick={() => handleSelectTemplate(t.key)}
                disabled={isGenerating}
                style={{ textAlign: "left", padding: "0.875rem 1rem", backgroundColor: isSelected ? "#1A1A1A" : "rgba(26,26,26,0.04)", color: isSelected ? "#F5EFE6" : "#1A1A1A", border: `1px solid ${isSelected ? "#1A1A1A" : "rgba(26,26,26,0.12)"}`, cursor: "pointer", transition: "all 0.15s ease", borderRadius: "2px" }}
              >
                <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "0.9375rem", fontWeight: 400, marginBottom: "2px" }}>{t.label}</p>
                <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.7rem", opacity: isSelected ? 0.6 : 0.4, letterSpacing: "0.02em" }}>
                  {isGenerating ? "Generating..." : isCached ? t.sub : t.sub}
                </p>
              </button>
            );
          })}
        </div>
        {genError && (
          <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.8125rem", color: "#E07856", marginTop: "0.75rem" }}>
            {genError} <button onClick={() => generateTemplate(selected)} style={{ background: "none", border: "none", color: "#E07856", textDecoration: "underline", cursor: "pointer", fontSize: "0.8125rem" }}>Retry</button>
          </p>
        )}
      </div>

      {/* Template area */}
      <div style={{ border: "1px solid rgba(26,26,26,0.1)", margin: "0 1.5rem 3rem", borderRadius: "2px", overflow: "hidden", maxWidth: "680px", marginLeft: "auto", marginRight: "auto", minHeight: "300px" }}>
        {loadingTemplate === selected ? (
          <div style={{ display: "flex", flexDirection: "column", alignItems: "center", justifyContent: "center", minHeight: "300px", gap: "1rem" }}>
            <style>{`@keyframes spin { to { transform: rotate(360deg); } }`}</style>
            <div style={{ width: "24px", height: "24px", border: "2px solid rgba(26,26,26,0.12)", borderTop: "2px solid #1A1A1A", borderRadius: "50%", animation: "spin 0.8s linear infinite" }} />
            <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontSize: "0.9375rem", opacity: 0.4 }}>
              Writing the other version...
            </p>
          </div>
        ) : fullData ? (
          <>
            {selected === "linkedin_ghost" && <LinkedInGhost data={fullData} />}
            {selected === "wiki_stub" && <WikiStub data={fullData} />}
            {selected === "museum_plaque" && <MuseumPlaque data={fullData} />}
            {selected === "tarot_card" && <TarotCard data={fullData} />}
          </>
        ) : (
          <div style={{ display: "flex", alignItems: "center", justifyContent: "center", minHeight: "300px" }}>
            <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", opacity: 0.3 }}>Click a template to generate it.</p>
          </div>
        )}
      </div>

    </main>
  );
}
