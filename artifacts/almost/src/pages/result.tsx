import { useState, useEffect, useRef } from "react";
import { useLocation } from "wouter";
import type { LifeData } from "@/lib/types";
import LinkedInGhost from "@/components/templates/LinkedInGhost";
import WikiStub from "@/components/templates/WikiStub";
import MuseumPlaque from "@/components/templates/MuseumPlaque";
import TarotCard from "@/components/templates/TarotCard";
import { clearSession } from "@/lib/session";
import StepProgress from "@/components/StepProgress";

type TemplateKey = "linkedin_ghost" | "wiki_stub" | "museum_plaque" | "tarot_card";

const TEMPLATE_LABELS: Record<TemplateKey, string> = {
  linkedin_ghost: "LinkedIn Ghost",
  wiki_stub: "The Wiki Stub",
  museum_plaque: "Museum Plaque",
  tarot_card: "The Tarot Card",
};

function buildDownload(containerEl: HTMLElement, name: string, label: string, templateKey: string) {
  const doc = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Almost — ${name} — ${label}</title>
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin="">
  <link href="https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,300;0,9..144,400;1,9..144,300;1,9..144,400&family=Inter:wght@300;400;500;600&display=swap" rel="stylesheet">
  <style>
    *, *::before, *::after { box-sizing: border-box; margin: 0; padding: 0; }
    html { -webkit-font-smoothing: antialiased; }
    body { background: #F5EFE6; }
    .almost-footer { text-align: center; padding: 2rem 1rem; font-family: 'Inter', sans-serif; font-size: 0.75rem; color: #1A1A1A; opacity: 0.3; letter-spacing: 0.04em; }
  </style>
</head>
<body>
  ${containerEl.innerHTML}
  <div class="almost-footer">Generated by Almost &middot; the life you didn't quite live</div>
</body>
</html>`;

  const blob = new Blob([doc], { type: "text/html;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `almost-${name.toLowerCase().replace(/\s+/g, "-")}-${templateKey}.html`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export default function Result() {
  const [, navigate] = useLocation();
  const [data, setData] = useState<LifeData | null>(null);
  const [template, setTemplate] = useState<TemplateKey>("linkedin_ghost");
  const [failed, setFailed] = useState(false);
  const templateRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const raw = sessionStorage.getItem("almost_life_result");
    const templateKey = (sessionStorage.getItem("almost_template_type") || "linkedin_ghost") as TemplateKey;
    setTemplate(templateKey);

    if (!raw) {
      if (!sessionStorage.getItem("almost_branch")) { navigate("/upload"); return; }
      setFailed(true);
      return;
    }
    try {
      setData(JSON.parse(raw));
    } catch {
      setFailed(true);
    }
  }, [navigate]);

  function handleDownload() {
    if (!data || !templateRef.current) return;
    buildDownload(templateRef.current, data.name, TEMPLATE_LABELS[template], template);
  }

  function handleTryDifferentFork() {
    sessionStorage.setItem("almost_return_mode", "fork");
    sessionStorage.removeItem("almost_branch");
    sessionStorage.removeItem("almost_life_result");
    navigate("/branches");
  }

  if (failed) {
    return (
      <main style={{ backgroundColor: "#F5EFE6", color: "#1A1A1A", minHeight: "100vh", display: "flex", flexDirection: "column", alignItems: "center", justifyContent: "center", padding: "2rem", gap: "1.5rem" }}>
        <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "2rem", fontWeight: 300 }}>Something went wrong.</h1>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.875rem", opacity: 0.5 }}>Generation may have timed out. Try again.</p>
        <button onClick={() => navigate("/template-picker")} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.8125rem", backgroundColor: "#1A1A1A", color: "#F5EFE6", border: "none", padding: "0.75rem 1.75rem", cursor: "pointer" }}>
          Try again
        </button>
      </main>
    );
  }

  if (!data) {
    return (
      <main style={{ backgroundColor: "#F5EFE6", minHeight: "100vh", display: "flex", alignItems: "center", justifyContent: "center" }}>
        <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", opacity: 0.4 }}>Assembling the other version...</p>
      </main>
    );
  }

  return (
    <main style={{ backgroundColor: "#F5EFE6", color: "#1A1A1A", minHeight: "100vh" }}>

      {/* Sticky header */}
      <div style={{ backgroundColor: "#F5EFE6", position: "sticky", top: 0, zIndex: 10 }}>
        <StepProgress current={4} />
        <div style={{ borderBottom: "1px solid rgba(26,26,26,0.1)", padding: "0.875rem 1.5rem", display: "flex", alignItems: "center", justifyContent: "space-between" }}>
          <button onClick={() => navigate("/template-picker")} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", color: "#1A1A1A", opacity: 0.4, letterSpacing: "0.04em", cursor: "pointer", background: "none", border: "none" }}>
            ← Change format
          </button>
          <button onClick={() => { clearSession(); navigate("/"); }} style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontSize: "0.875rem", color: "#1A1A1A", opacity: 0.5, background: "none", border: "none", cursor: "pointer" }}>
            Almost
          </button>
          <button onClick={handleDownload} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", backgroundColor: "#1A1A1A", color: "#F5EFE6", border: "none", padding: "0.5rem 1.25rem", cursor: "pointer", letterSpacing: "0.04em" }}>
            Download →
          </button>
        </div>
      </div>

      {/* Fork summary */}
      <div style={{ padding: "2.5rem 1.5rem 1.5rem", maxWidth: "680px", margin: "0 auto" }}>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", letterSpacing: "0.1em", textTransform: "uppercase", opacity: 0.35, marginBottom: "0.5rem" }}>
          {data.year_of_fork} · the road not taken
        </p>
        <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "clamp(1.5rem, 4vw, 2rem)", fontWeight: 300, lineHeight: 1.2, marginBottom: "0.4rem" }}>
          {data.fork_summary}
        </h1>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.875rem", opacity: 0.5 }}>
          {data.alt_role} · {data.alt_location}
        </p>
      </div>

      {/* Template label pill */}
      <div style={{ padding: "0 1.5rem 1.5rem", maxWidth: "680px", margin: "0 auto" }}>
        <span style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.6875rem", letterSpacing: "0.08em", textTransform: "uppercase", backgroundColor: "#1A1A1A", color: "#F5EFE6", padding: "0.3rem 0.75rem", borderRadius: "2px" }}>
          {TEMPLATE_LABELS[template]}
        </span>
      </div>

      {/* Template render */}
      <div ref={templateRef} style={{ border: "1px solid rgba(26,26,26,0.1)", margin: "0 1.5rem 2rem", borderRadius: "2px", overflow: "hidden", maxWidth: "680px", marginLeft: "auto", marginRight: "auto" }}>
        {template === "linkedin_ghost" && <LinkedInGhost data={data} />}
        {template === "wiki_stub" && <WikiStub data={data} />}
        {template === "museum_plaque" && <MuseumPlaque data={data} />}
        {template === "tarot_card" && <TarotCard data={data} />}
      </div>

      {/* Bottom actions */}
      <div style={{ display: "flex", flexWrap: "wrap", justifyContent: "center", alignItems: "center", gap: "0.75rem 1.5rem", paddingBottom: "3rem", padding: "0 1.5rem 3rem" }}>
        <button
          onClick={handleTryDifferentFork}
          style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.8125rem", backgroundColor: "#E07856", color: "#fff", border: "none", padding: "0.65rem 1.5rem", cursor: "pointer", letterSpacing: "0.04em", borderRadius: "2px" }}
        >
          ↩ Try a different fork
        </button>
        <button
          onClick={() => navigate("/template-picker")}
          style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.8125rem", background: "none", border: "1px solid rgba(26,26,26,0.2)", color: "#1A1A1A", padding: "0.625rem 1.5rem", cursor: "pointer", letterSpacing: "0.04em", borderRadius: "2px" }}
        >
          Try a different format →
        </button>
        <button
          onClick={() => { clearSession(); navigate("/"); }}
          style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.8125rem", background: "none", border: "none", color: "#1A1A1A", opacity: 0.3, cursor: "pointer", letterSpacing: "0.04em" }}
        >
          Start over
        </button>
      </div>

    </main>
  );
}
