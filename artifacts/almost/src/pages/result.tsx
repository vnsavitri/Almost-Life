function buildDownload(containerEl: HTMLElement, name: string, label: string, templateKey: string) {
  const doc = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Almost — ${name} — ${label}</title>
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin="">
  <link href="https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,300;0,9..144,400;1,9..144,300;1,9..144,400&family=Inter:wght@300;400;500;600&display=swap" rel="stylesheet">
  <style>*,*::before,*::after{box-sizing:border-box;margin:0;padding:0}html{-webkit-font-smoothing:antialiased}body{background:#BCD2EE}.almost-footer{text-align:center;padding:2rem 1rem;font-family:'Inter',sans-serif;font-size:0.75rem;color:#52050A;opacity:0.25;letter-spacing:0.06em}</style>
</head>
<body>${containerEl.innerHTML}<div class="almost-footer">Generated by Almost · the life you didn't quite live</div></body>
</html>`;
  const blob = new Blob([doc], { type: "text/html;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `almost-${name.toLowerCase().replace(/\s+/g, "-")}-${templateKey}.html`;
  document.body.appendChild(a); a.click(); document.body.removeChild(a); URL.revokeObjectURL(url);
}

interface ShareModalProps { data: LifeData; template: TemplateKey; onClose: () => void; }

function ShareModal({ data, template, onClose }: ShareModalProps) {
  const [copied, setCopied] = useState<"link" | "discord" | null>(null);
  const payload = buildSharePayload(data, template);
  const shareUrl = buildShareUrl(payload);

  function copyLink() { navigator.clipboard.writeText(shareUrl).then(() => { setCopied("link"); setTimeout(() => setCopied(null), 2000); }); }
  function copyDiscord() { navigator.clipboard.writeText(discordText(payload, shareUrl)).then(() => { setCopied("discord"); setTimeout(() => setCopied(null), 2000); }); }

  return (
    <div onClick={onClose} style={{ position: "fixed", inset: 0, backgroundColor: "rgba(82,5,10,0.6)", zIndex: 100, display: "flex", alignItems: "center", justifyContent: "center", padding: "1.5rem" }}>
      <div onClick={e => e.stopPropagation()} style={{ backgroundColor: "#BCD2EE", width: "100%", maxWidth: "420px", overflow: "hidden" }}>
        {/* Dark preview card */}
        <div style={{ backgroundColor: "#52050A", padding: "2rem 2rem 1.75rem" }}>
          <div style={{ display: "flex", justifyContent: "space-between", marginBottom: "1.25rem" }}>
            <span style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontSize: "0.875rem", color: "#BCD2EE", opacity: 0.3 }}>Almost</span>
            <span style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.5rem", letterSpacing: "0.14em", textTransform: "uppercase", color: "#BCD2EE", opacity: 0.4 }}>the life you didn't quite live</span>
          </div>
          <div style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontWeight: 200, fontSize: "clamp(2.5rem, 12vw, 3.5rem)", color: "#832161", opacity: 0.85, lineHeight: 0.9, marginBottom: "1rem" }}>
            {payload.y}
          </div>
          <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "0.9375rem", fontWeight: 300, color: "#BCD2EE", lineHeight: 1.35, marginBottom: "0.5rem", maxWidth: "32ch" }}>
            {payload.fs}
          </p>
          <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.6875rem", color: "#BCD2EE", opacity: 0.35, letterSpacing: "0.04em" }}>
            {payload.ar} · {payload.al}
          </p>
        </div>

        {/* Actions */}
        <div style={{ padding: "1.5rem" }}>
          <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.5625rem", letterSpacing: "0.14em", textTransform: "uppercase", color: "#52050A", opacity: 0.35, marginBottom: "1.25rem" }}>
            Share your alternate life
          </p>
          <div style={{ display: "flex", flexDirection: "column", gap: "0.5rem" }}>
            <button onClick={copyLink} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", letterSpacing: "0.06em", textTransform: "uppercase", backgroundColor: "#52050A", color: "#BCD2EE", border: "none", padding: "0.75rem", cursor: "pointer", textAlign: "center" }}>
              {copied === "link" ? "✓ Copied" : "Copy link"}
            </button>
            <a href={xShareUrl(payload, shareUrl)} target="_blank" rel="noopener noreferrer" style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", letterSpacing: "0.06em", textTransform: "uppercase", backgroundColor: "#000", color: "#fff", padding: "0.75rem", cursor: "pointer", textAlign: "center", textDecoration: "none", display: "block" }}>
              Post on X
            </a>
            <a href={linkedInShareUrl(payload, shareUrl)} target="_blank" rel="noopener noreferrer" style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", letterSpacing: "0.06em", textTransform: "uppercase", backgroundColor: "#0A66C2", color: "#fff", padding: "0.75rem", cursor: "pointer", textAlign: "center", textDecoration: "none", display: "block" }}>
              Share on LinkedIn
            </a>
            <button onClick={copyDiscord} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", letterSpacing: "0.06em", textTransform: "uppercase", backgroundColor: "#5865F2", color: "#fff", border: "none", padding: "0.75rem", cursor: "pointer", textAlign: "center" }}>
              {copied === "discord" ? "✓ Copied for Discord" : "Copy for Discord"}
            </button>
          </div>
          <button onClick={onClose} style={{ marginTop: "1rem", width: "100%", background: "none", border: "none", fontFamily: "'Inter', sans-serif", fontSize: "0.625rem", letterSpacing: "0.1em", textTransform: "uppercase", color: "#52050A", opacity: 0.25, cursor: "pointer", padding: "0.25rem" }}>
            Close
          </button>
        </div>
      </div>
    </div>
  );
}

export default function Result() {
  const [, navigate] = useLocation();
  const [data, setData] = useState<LifeData | null>(null);
  const [template, setTemplate] = useState<TemplateKey>("linkedin_ghost");
  const [failed, setFailed] = useState(false);
  const [shareOpen, setShareOpen] = useState(false);
  const templateRef = useRef<HTMLDivElement>(null);

  const [rateLimited, setRateLimited] = useState<{ reset_in_hours: number } | null>(null);

  useEffect(() => {
    const rlRaw = sessionStorage.getItem("almost_rate_limited");
    if (rlRaw) {
      sessionStorage.removeItem("almost_rate_limited");
      try { setRateLimited(JSON.parse(rlRaw)); } catch { setRateLimited({ reset_in_hours: 24 }); }
      return;
    }
    const raw = sessionStorage.getItem("almost_life_result");
    const templateKey = (sessionStorage.getItem("almost_template_type") || "linkedin_ghost") as TemplateKey;
    setTemplate(templateKey);
    if (!raw) { if (!sessionStorage.getItem("almost_branch")) { navigate("/upload"); return; } setFailed(true); return; }
    try { setData(JSON.parse(raw)); } catch { setFailed(true); }
  }, [navigate]);

  useEffect(() => { document.body.style.overflow = shareOpen ? "hidden" : ""; return () => { document.body.style.overflow = ""; }; }, [shareOpen]);

  function handleDownload() {
    if (!data || !templateRef.current) return;
    buildDownload(templateRef.current, data.name, TEMPLATE_LABELS[template], template);
  }

  function handleTryDifferentFork() {
    sessionStorage.setItem("almost_return_mode", "fork");
    sessionStorage.removeItem("almost_branch");
    sessionStorage.removeItem("almost_life_result");
    navigate("/branches");
  }

  if (rateLimited) {
    return (
      <main className="grain" style={{ backgroundColor: "#BCD2EE", color: "#52050A", minHeight: "100vh", display: "flex", flexDirection: "column", alignItems: "center", justifyContent: "center", padding: "2rem" }}>
        <div style={{ maxWidth: "480px", width: "100%", textAlign: "left" }}>
          <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.5625rem", letterSpacing: "0.16em", textTransform: "uppercase", color: "#832161", opacity: 0.6, marginBottom: "1.5rem" }}>
            Limit reached
          </p>
          <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontWeight: 300, fontSize: "clamp(1.75rem, 6vw, 2.5rem)", lineHeight: 1.15, marginBottom: "1.25rem" }}>
            You've generated your 3 lives for today.
          </h1>
          <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontWeight: 300, fontSize: "1rem", color: "#52050A", opacity: 0.55, lineHeight: 1.6, marginBottom: "2.5rem" }}>
            The other versions of you will still be there in ~{rateLimited.reset_in_hours}h. Come back tomorrow.
          </p>
          <div style={{ borderTop: "1px solid rgba(82,5,10,0.1)", paddingTop: "1.5rem", display: "flex", gap: "2rem" }}>
            <button onClick={() => navigate("/")} className="ruled-action">← Home</button>
            <button onClick={() => navigate("/about")} className="ruled-action">About Almost</button>
          </div>
        </div>
      </main>
    );
  }

  if (failed) {
    return (
      <main className="grain" style={{ backgroundColor: "#BCD2EE", color: "#52050A", minHeight: "100vh", display: "flex", flexDirection: "column", alignItems: "center", justifyContent: "center", gap: "1.5rem", padding: "2rem" }}>
        <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "2rem", fontWeight: 300 }}>Something went wrong.</h1>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.875rem", opacity: 0.4 }}>Generation may have timed out.</p>
        <button onClick={() => navigate("/template-picker")} className="ruled-action">← Try again</button>
      </main>
    );
  }

  if (!data) {
    return (
      <main style={{ backgroundColor: "#BCD2EE", minHeight: "100vh", display: "flex", alignItems: "center", justifyContent: "center" }}>
        <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", opacity: 0.35 }}>Assembling the other version...</p>
      </main>
    );
  }

  return (
    <main className="grain" style={{ backgroundColor: "#BCD2EE", color: "#52050A", minHeight: "100vh" }}>
      {shareOpen && <ShareModal data={data} template={template} onClose={() => setShareOpen(false)} />}

      {/* Sticky header */}
      <div style={{ backgroundColor: "#BCD2EE", position: "sticky", top: 0, zIndex: 10 }}>
        <StepProgress current={4} />
        <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", padding: "0.875rem 2rem", borderBottom: "1px solid rgba(82,5,10,0.08)", gap: "1rem" }}>
          <button onClick={() => navigate("/template-picker")} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.5625rem", letterSpacing: "0.12em", textTransform: "uppercase", color: "#52050A", opacity: 0.3, background: "none", border: "none", cursor: "pointer", flexShrink: 0 }}>
            ← Format
          </button>
          <button onClick={() => { clearSession(); navigate("/"); }} style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontSize: "0.9375rem", color: "#52050A", opacity: 0.4, background: "none", border: "none", cursor: "pointer" }}>
            Almost
          </button>
          <div style={{ display: "flex", gap: "0.75rem", alignItems: "center", flexShrink: 0 }}>
            <button onClick={() => setShareOpen(true)} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.5625rem", letterSpacing: "0.12em", textTransform: "uppercase", color: "#52050A", opacity: 0.4, background: "none", border: "none", cursor: "pointer" }}>
              Share ↗
            </button>
            <button onClick={handleDownload} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.5625rem", letterSpacing: "0.12em", textTransform: "uppercase", backgroundColor: "#52050A", color: "#BCD2EE", border: "none", padding: "0.5rem 1rem", cursor: "pointer" }}>
              Download →
            </button>
          </div>
        </div>
      </div>

      {/* Fork headline */}
      <div style={{ maxWidth: "760px", margin: "0 auto", padding: "3rem 2rem 1.5rem" }}>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.5625rem", letterSpacing: "0.16em", textTransform: "uppercase", color: "#832161", opacity: 0.6, marginBottom: "0.75rem" }}>
          {data.year_of_fork} · the road not taken
        </p>
        <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "clamp(1.5rem, 3.5vw, 2.25rem)", fontWeight: 300, letterSpacing: "-0.02em", lineHeight: 1.15, marginBottom: "0.75rem" }}>
          {data.fork_summary}
        </h1>
        <div style={{ display: "flex", alignItems: "center", gap: "1rem" }}>
          <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontSize: "0.9375rem", color: "#52050A", opacity: 0.4 }}>
            {data.alt_role} · {data.alt_location}
          </p>
          <span style={{ height: "1px", width: "1rem", backgroundColor: "rgba(82,5,10,0.15)", flexShrink: 0 }} />
          <span style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.5rem", letterSpacing: "0.1em", textTransform: "uppercase", color: "#52050A", opacity: 0.3 }}>{TEMPLATE_LABELS[template]}</span>
        </div>
      </div>

      {/* Template */}
      <div ref={templateRef} style={{ border: "1px solid rgba(82,5,10,0.1)", margin: "1rem 2rem 0", maxWidth: "760px", marginLeft: "auto", marginRight: "auto", overflow: "hidden" }}>
        {template === "linkedin_ghost" && <LinkedInGhost data={data} />}
        {template === "wiki_stub" && <WikiStub data={data} />}
        {template === "museum_plaque" && <MuseumPlaque data={data} />}
        {template === "tarot_card" && <TarotCard data={data} />}
      </div>

      {/* Bottom actions */}
      <div style={{ maxWidth: "760px", margin: "0 auto", padding: "2rem 2rem 4rem", display: "flex", justifyContent: "space-between", alignItems: "center", flexWrap: "wrap", gap: "1rem", borderTop: "1px solid rgba(82,5,10,0.06)", marginTop: "2rem" }}>
        <div style={{ display: "flex", gap: "2rem", alignItems: "center" }}>
          <button onClick={handleTryDifferentFork} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.6875rem", letterSpacing: "0.08em", textTransform: "uppercase", color: "#832161", background: "none", border: "none", cursor: "pointer" }}>
            ↩ Different fork
          </button>
          <button onClick={() => navigate("/template-picker")} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.6875rem", letterSpacing: "0.08em", textTransform: "uppercase", color: "#52050A", opacity: 0.4, background: "none", border: "none", cursor: "pointer" }}>
            Different format →
          </button>
        </div>
        <div style={{ display: "flex", gap: "2rem", alignItems: "center" }}>
          <button onClick={() => setShareOpen(true)} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.6875rem", letterSpacing: "0.08em", textTransform: "uppercase", color: "#52050A", opacity: 0.3, background: "none", border: "none", cursor: "pointer" }}>
            Share ↗
          </button>
          <button onClick={() => { clearSession(); navigate("/"); }} style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.6875rem", letterSpacing: "0.08em", textTransform: "uppercase", color: "#52050A", opacity: 0.2, background: "none", border: "none", cursor: "pointer" }}>
            Start over
          </button>
        </div>
      </div>
    </main>
  );
}
