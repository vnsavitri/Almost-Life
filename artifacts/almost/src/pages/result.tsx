import { useState, useEffect } from "react";
import { useLocation, Link } from "wouter";
import type { LifeData } from "@/lib/types";
import LinkedInGhost from "@/components/templates/LinkedInGhost";
import WikiStub from "@/components/templates/WikiStub";
import MuseumPlaque from "@/components/templates/MuseumPlaque";
import TarotCard from "@/components/templates/TarotCard";

type TemplateKey = "linkedin_ghost" | "wiki_stub" | "museum_plaque" | "tarot_card";

const TEMPLATE_LABELS: Record<TemplateKey, string> = {
  linkedin_ghost: "LinkedIn Ghost",
  wiki_stub: "The Wiki Stub",
  museum_plaque: "Museum Plaque",
  tarot_card: "The Tarot Card",
};

function downloadHtml(data: LifeData, template: TemplateKey) {
  const label = TEMPLATE_LABELS[template];
  const blob = new Blob([
    `<!DOCTYPE html><html lang="en"><head><meta charset="UTF-8">` +
    `<meta name="viewport" content="width=device-width, initial-scale=1.0">` +
    `<title>Almost — ${data.name} — ${label}</title>` +
    `<link href="https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,300;0,9..144,400;1,9..144,300&family=Inter:wght@300;400;500&display=swap" rel="stylesheet">` +
    `<style>*{box-sizing:border-box;margin:0;padding:0}body{font-family:'Inter',sans-serif;background:#F5EFE6}` +
    `.footer{text-align:center;padding:2rem;font-family:'Inter',sans-serif;font-size:.75rem;opacity:.3;color:#1A1A1A}</style></head>` +
    `<body><p class="footer">Generated by Almost · the life you didn't quite live</p></body></html>`
  ], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `almost-${data.name.toLowerCase().replace(/\s+/g, "-")}-${template}.html`;
  a.click();
  URL.revokeObjectURL(url);
}

export default function Result() {
  const [, navigate] = useLocation();
  const [data, setData] = useState<LifeData | null>(null);
  const [template, setTemplate] = useState<TemplateKey>("linkedin_ghost");
  const [failed, setFailed] = useState(false);

  useEffect(() => {
    const raw = sessionStorage.getItem("almost_life_result");
    const templateKey = (sessionStorage.getItem("almost_template_type") || "linkedin_ghost") as TemplateKey;
    setTemplate(templateKey);

    if (!raw) {
      if (!sessionStorage.getItem("almost_branch")) { navigate("/upload"); return; }
      setFailed(true);
      return;
    }
    try {
      setData(JSON.parse(raw));
    } catch {
      setFailed(true);
    }
  }, [navigate]);

  if (failed) {
    return (
      <main style={{ backgroundColor: "#F5EFE6", color: "#1A1A1A", minHeight: "100vh", display: "flex", flexDirection: "column", alignItems: "center", justifyContent: "center", padding: "2rem", gap: "1.5rem" }}>
        <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "2rem", fontWeight: 300 }}>Something went wrong.</h1>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.875rem", opacity: 0.5 }}>Generation may have timed out. Try again.</p>
        <button
          onClick={() => navigate("/template-picker")}
          style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.8125rem", backgroundColor: "#1A1A1A", color: "#F5EFE6", border: "none", padding: "0.75rem 1.75rem", cursor: "pointer" }}
        >
          Try again
        </button>
      </main>
    );
  }

  if (!data) {
    return (
      <main style={{ backgroundColor: "#F5EFE6", minHeight: "100vh", display: "flex", alignItems: "center", justifyContent: "center" }}>
        <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", opacity: 0.4 }}>Assembling the other version...</p>
      </main>
    );
  }

  return (
    <main style={{ backgroundColor: "#F5EFE6", color: "#1A1A1A", minHeight: "100vh" }}>

      {/* Header */}
      <div style={{ backgroundColor: "#F5EFE6", borderBottom: "1px solid rgba(26,26,26,0.1)", padding: "1rem 1.5rem", display: "flex", alignItems: "center", justifyContent: "space-between", position: "sticky", top: 0, zIndex: 10 }}>
        <Link href="/template-picker">
          <span style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", color: "#1A1A1A", opacity: 0.4, letterSpacing: "0.04em", cursor: "pointer" }}>
            ← Try another format
          </span>
        </Link>
        <span style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontSize: "0.875rem", opacity: 0.5 }}>Almost</span>
        <button
          onClick={() => downloadHtml(data, template)}
          style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", backgroundColor: "#1A1A1A", color: "#F5EFE6", border: "none", padding: "0.5rem 1.25rem", cursor: "pointer", letterSpacing: "0.04em" }}
        >
          Download →
        </button>
      </div>

      {/* Fork summary */}
      <div style={{ padding: "2.5rem 1.5rem 1.5rem", maxWidth: "680px", margin: "0 auto" }}>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", letterSpacing: "0.1em", textTransform: "uppercase", opacity: 0.35, marginBottom: "0.5rem" }}>
          {data.year_of_fork} · the road not taken
        </p>
        <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "clamp(1.5rem, 4vw, 2rem)", fontWeight: 300, lineHeight: 1.2, marginBottom: "0.4rem" }}>
          {data.fork_summary}
        </h1>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.875rem", opacity: 0.5 }}>
          {data.alt_role} · {data.alt_location}
        </p>
      </div>

      {/* Template label pill */}
      <div style={{ padding: "0 1.5rem 1.5rem", maxWidth: "680px", margin: "0 auto" }}>
        <span style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.6875rem", letterSpacing: "0.08em", textTransform: "uppercase", backgroundColor: "#1A1A1A", color: "#F5EFE6", padding: "0.3rem 0.75rem", borderRadius: "2px" }}>
          {TEMPLATE_LABELS[template]}
        </span>
      </div>

      {/* Template */}
      <div style={{ border: "1px solid rgba(26,26,26,0.1)", margin: "0 1.5rem 2rem", borderRadius: "2px", overflow: "hidden", maxWidth: "680px", marginLeft: "auto", marginRight: "auto" }}>
        {template === "linkedin_ghost" && <LinkedInGhost data={data} />}
        {template === "wiki_stub" && <WikiStub data={data} />}
        {template === "museum_plaque" && <MuseumPlaque data={data} />}
        {template === "tarot_card" && <TarotCard data={data} />}
      </div>

      {/* Try another */}
      <div style={{ textAlign: "center", paddingBottom: "3rem" }}>
        <button
          onClick={() => navigate("/template-picker")}
          style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.8125rem", background: "none", border: "1px solid rgba(26,26,26,0.2)", color: "#1A1A1A", padding: "0.625rem 1.5rem", cursor: "pointer", letterSpacing: "0.04em", borderRadius: "2px" }}
        >
          Try a different format →
        </button>
      </div>

    </main>
  );
}
