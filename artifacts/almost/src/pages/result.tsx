import { useState, useEffect } from "react";
import { useLocation, Link } from "wouter";
import type { LifeData } from "@/lib/types";
import LinkedInGhost from "@/components/templates/LinkedInGhost";
import WikiStub from "@/components/templates/WikiStub";
import MuseumPlaque from "@/components/templates/MuseumPlaque";
import TarotCard from "@/components/templates/TarotCard";

type TemplateKey = "linkedin_ghost" | "wiki_stub" | "museum_plaque" | "tarot_card";

const TEMPLATES: { key: TemplateKey; label: string; sub: string }[] = [
  { key: "linkedin_ghost", label: "LinkedIn Ghost", sub: "Other You, hireable" },
  { key: "wiki_stub", label: "The Wiki Stub", sub: "Notable. Probably." },
  { key: "museum_plaque", label: "Museum Plaque", sub: "80 words. All restraint." },
  { key: "tarot_card", label: "The Tarot Card", sub: "Cards don't lie." },
];

function downloadHtml(data: LifeData, template: TemplateKey) {
  const titles: Record<TemplateKey, string> = {
    linkedin_ghost: "LinkedIn Ghost",
    wiki_stub: "Wiki Stub",
    museum_plaque: "Museum Plaque",
    tarot_card: "Tarot Card",
  };

  const htmlContent = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Almost — ${data.name} — ${titles[template]}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,300;0,9..144,400;1,9..144,300&family=Inter:wght@300;400;500&display=swap" rel="stylesheet">
<style>
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { font-family: 'Inter', sans-serif; }
  .almost-footer { text-align: center; padding: 2rem; font-family: 'Inter', sans-serif; font-size: 0.75rem; opacity: 0.3; color: #1A1A1A; background: #F5EFE6; }
</style>
</head>
<body>
<div id="content"><!-- Generated by Almost — the life you didn't quite live --></div>
<div class="almost-footer">Generated by Almost &middot; the life you didn't quite live</div>
</body>
</html>`;

  const blob = new Blob([htmlContent], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `almost-${data.name.toLowerCase().replace(/\s+/g, "-")}-${template}.html`;
  a.click();
  URL.revokeObjectURL(url);
}

export default function Result() {
  const [, navigate] = useLocation();
  const [data, setData] = useState<LifeData | null>(null);
  const [selected, setSelected] = useState<TemplateKey>("linkedin_ghost");
  const [error, setError] = useState(false);

  useEffect(() => {
    const raw = sessionStorage.getItem("almost_life");
    if (!raw) {
      // No life data — went to result before generation finished or directly
      const branchRaw = sessionStorage.getItem("almost_branch");
      if (!branchRaw) { navigate("/upload"); return; }
      setError(true);
      return;
    }
    try {
      setData(JSON.parse(raw));
    } catch {
      setError(true);
    }
  }, [navigate]);

  if (error) {
    return (
      <main style={{ backgroundColor: "#F5EFE6", color: "#1A1A1A", minHeight: "100vh", display: "flex", flexDirection: "column", alignItems: "center", justifyContent: "center", padding: "2rem" }}>
        <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "2rem", fontWeight: 300, marginBottom: "1rem" }}>Something went wrong.</h1>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.875rem", opacity: 0.5, marginBottom: "2rem" }}>The generation may have failed. Try again from the beginning.</p>
        <Link href="/upload">
          <button style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.8125rem", backgroundColor: "#1A1A1A", color: "#F5EFE6", border: "none", padding: "0.75rem 1.75rem", cursor: "pointer" }}>
            Start over
          </button>
        </Link>
      </main>
    );
  }

  if (!data) {
    return (
      <main style={{ backgroundColor: "#F5EFE6", minHeight: "100vh", display: "flex", alignItems: "center", justifyContent: "center" }}>
        <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", opacity: 0.4 }}>Assembling the other version...</p>
      </main>
    );
  }

  return (
    <main style={{ backgroundColor: "#F5EFE6", color: "#1A1A1A", minHeight: "100vh" }}>

      {/* Header bar */}
      <div style={{ backgroundColor: "#F5EFE6", borderBottom: "1px solid rgba(26,26,26,0.1)", padding: "1rem 1.5rem", display: "flex", alignItems: "center", justifyContent: "space-between", position: "sticky", top: 0, zIndex: 10 }}>
        <Link href="/branches">
          <span style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", color: "#1A1A1A", opacity: 0.4, letterSpacing: "0.04em", cursor: "pointer" }}>
            ← Try another fork
          </span>
        </Link>
        <span style={{ fontFamily: "'Fraunces', Georgia, serif", fontStyle: "italic", fontSize: "0.875rem", opacity: 0.5 }}>Almost</span>
        <button
          onClick={() => downloadHtml(data, selected)}
          style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", backgroundColor: "#1A1A1A", color: "#F5EFE6", border: "none", padding: "0.5rem 1.25rem", cursor: "pointer", letterSpacing: "0.04em" }}
        >
          Download →
        </button>
      </div>

      {/* Fork summary */}
      <div style={{ padding: "2.5rem 1.5rem 1.5rem", maxWidth: "680px", margin: "0 auto" }}>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.75rem", letterSpacing: "0.1em", textTransform: "uppercase", opacity: 0.35, marginBottom: "0.5rem" }}>
          {data.year_of_fork} · the road not taken
        </p>
        <h1 style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "clamp(1.5rem, 4vw, 2rem)", fontWeight: 300, lineHeight: 1.2, marginBottom: "0.4rem" }}>
          {data.fork_summary}
        </h1>
        <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.875rem", opacity: 0.5 }}>
          {data.alt_role} · {data.alt_location}
        </p>
      </div>

      {/* Template picker */}
      <div style={{ padding: "0 1.5rem 1.5rem", maxWidth: "680px", margin: "0 auto" }}>
        <div style={{ display: "grid", gridTemplateColumns: "repeat(2, 1fr)", gap: "0.5rem" }}>
          {TEMPLATES.map((t) => (
            <button
              key={t.key}
              onClick={() => setSelected(t.key)}
              style={{
                textAlign: "left",
                padding: "0.875rem 1rem",
                backgroundColor: selected === t.key ? "#1A1A1A" : "rgba(26,26,26,0.04)",
                color: selected === t.key ? "#F5EFE6" : "#1A1A1A",
                border: `1px solid ${selected === t.key ? "#1A1A1A" : "rgba(26,26,26,0.12)"}`,
                cursor: "pointer",
                transition: "all 0.15s ease",
                borderRadius: "2px",
              }}
            >
              <p style={{ fontFamily: "'Fraunces', Georgia, serif", fontSize: "0.9375rem", fontWeight: 400, marginBottom: "2px" }}>{t.label}</p>
              <p style={{ fontFamily: "'Inter', sans-serif", fontSize: "0.7rem", opacity: selected === t.key ? 0.6 : 0.4, letterSpacing: "0.02em" }}>{t.sub}</p>
            </button>
          ))}
        </div>
      </div>

      {/* Template render */}
      <div style={{ border: "1px solid rgba(26,26,26,0.1)", margin: "0 1.5rem 3rem", borderRadius: "2px", overflow: "hidden", maxWidth: "680px", marginLeft: "auto", marginRight: "auto" }}>
        {selected === "linkedin_ghost" && <LinkedInGhost data={data} />}
        {selected === "wiki_stub" && <WikiStub data={data} />}
        {selected === "museum_plaque" && <MuseumPlaque data={data} />}
        {selected === "tarot_card" && <TarotCard data={data} />}
      </div>

    </main>
  );
}
